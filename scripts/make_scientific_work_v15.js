/**
 * Таблица. Ширины в DXA и на таблице, и на каждой ячейке: проценты
 * разъезжаются в Google Docs.
 */
function table(headers, rows, widths) {
  const total = widths.reduce((a, b) => a + b, 0);
  const cell = (text, opts = {}) => new TableCell({
    width: { size: opts.width, type: WidthType.DXA },
    shading: opts.fill ? { type: ShadingType.CLEAR, fill: opts.fill, color: "auto" } : undefined,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    children: [new Paragraph({
      alignment: opts.align || AlignmentType.LEFT,
      spacing: { line: 240, after: 0 },
      children: [new TextRun({ text: String(text), font: FONT, size: 22,
                               bold: opts.bold, color: opts.color || INK })],
    })],
  });

  return new Table({
    width: { size: total, type: WidthType.DXA },
    columnWidths: widths,
    rows: [
      new TableRow({
        tableHeader: true,
        children: headers.map((text, i) =>
          cell(text, { width: widths[i], bold: true, fill: "E7EAF2" })),
      }),
      ...rows.map((row) => new TableRow({
        children: row.map((text, i) => cell(text, { width: widths[i] })),
      })),
    ],
  });
}

