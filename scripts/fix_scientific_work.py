def scale_figures(xml: str) -> tuple[str, int, int]:
    """Сжать графики, не тронув формулы.

    Размер картинки записан дважды: в ``wp:extent`` для места в тексте и в
    ``a:ext`` для самой картинки. Менять нужно оба и согласованно, поэтому
    документ режется по ``</w:drawing>``: внутри одного куска обе записи
    относятся к одной и той же картинке.
    """
    pattern = re.compile(r'<(wp:extent|a:ext) cx="(\d+)" cy="(\d+)"')
    chunks = xml.split("</w:drawing>")
    scaled = 0
    left_alone = 0

    for index, chunk in enumerate(chunks):
        first = pattern.search(chunk)
        if first is None:
            continue
        if int(first.group(3)) < FORMULA_HEIGHT_EMU:
            left_alone += 1
            continue

        def shrink(match: re.Match[str]) -> str:
            tag, cx, cy = match.group(1), int(match.group(2)), int(match.group(3))
            return f'<{tag} cx="{int(cx * FIGURE_SCALE)}" cy="{int(cy * FIGURE_SCALE)}"'

        chunks[index] = pattern.sub(shrink, chunk)
        scaled += 1

    return "</w:drawing>".join(chunks), scaled, left_alone


def edit_xml(path: Path) -> None:
    """Замены в тексте и масштаб рисунков."""
    xml = path.read_text(encoding="utf-8")
    missed: list[str] = []

    for old, new, label in REPLACEMENTS:
        if old == new:
            continue
        if old in xml:
            xml = xml.replace(old, new, 1)
        else:
            missed.append(label)

    # Заголовки таблицы меняются через метки: иначе новое значение одного
    # столбца попадает под замену следующего.
    for index, (old, new) in enumerate(TABLE_HEADERS):
        xml = xml.replace(f"<w:t>{old}</w:t>", f"<w:t>@@H{index}@@</w:t>", 1)
    xml = xml.replace("<w:t>ROC-AUC</w:t>", "<w:t>Что это</w:t>", 1)
    for index, (_, new) in enumerate(TABLE_HEADERS):
        xml = xml.replace(f"<w:t>@@H{index}@@</w:t>", f"<w:t>{new}</w:t>", 1)

    for old, new in TABLE_CELLS:
        if f"<w:t>{old}</w:t>" in xml:
            xml = xml.replace(f"<w:t>{old}</w:t>", f"<w:t>{new}</w:t>", 1)
        else:
            missed.append(f"ячейка «{old}»")

    xml, scaled, left_alone = scale_figures(xml)
    print(f"  сжато графиков: {scaled}, формул оставлено как есть: {left_alone}")

    path.write_text(xml, encoding="utf-8")
    if missed:
        print(f"  не найдено ({len(missed)}): {', '.join(missed)}")


def drop_paragraphs(path: Path) -> int:
    """Удаление абзацев-пересказов средствами python-docx.

    Вырезание из XML руками однажды порвало поле оглавления, и валидатор это
    поймал. Здесь абзац удаляется вместе со своим элементом целиком.
    """
    import docx

    document = docx.Document(str(path))
    removed = 0
    for paragraph in list(document.paragraphs):
        if any(paragraph.text.strip().startswith(m) for m in DROP_PARAGRAPHS):
            element = paragraph._element
            element.getparent().remove(element)
            removed += 1
    document.save(str(path))
    return removed


